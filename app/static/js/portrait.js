/* Binary portrait renderer.
   Reads the grid generated by tools/make_portrait.py (embedded in the page as
   JSON) and draws it as 0s and 1s in three layers.
   Uses only safe DOM APIs (no innerHTML) so the strict Content-Security-Policy
   with Trusted Types stays enforced. */
(function () {
  "use strict";
  var dataEl = document.getElementById("portrait-data");
  var wrap = document.querySelector(".portrait-wrap");
  if (!dataEl || !wrap) return;
  var P;
  try { P = JSON.parse(dataEl.textContent); } catch (e) { return; }
  if (!P || !P.layers) return;

  var portrait = document.createElement("div");
  portrait.className = "portrait";
  portrait.style.height = P.height + "px";
  portrait.setAttribute("aria-hidden", "true");

  P.layers.forEach(function (L) {
    var layer = document.createElement("div");
    layer.className = "layer " + String(L.name).replace(/[^a-z]/g, "");
    layer.style.top = Number(L.top) + "px";
    layer.style.setProperty("--cell", Number(L.cell) + "px");
    layer.style.setProperty("--fs", Number(L.cell) * (L.name === "sml" ? 1.18 : 1.0) + "px");
    var frag = document.createDocumentFragment();
    L.rows.forEach(function (row) {
      var r = document.createElement("div");
      r.className = "row";
      for (var i = 0; i < row.length; i++) {
        var ch = row.charAt(i);
        var s = document.createElement("span");
        if (ch >= "2" && ch <= "9") {
          s.className = "c l" + ch;
          s.textContent = Math.random() < 0.5 ? "0" : "1";
        } else {
          s.className = "c e";
        }
        r.appendChild(s);
      }
      frag.appendChild(r);
    });
    layer.appendChild(frag);
    portrait.appendChild(layer);
  });
  wrap.insertBefore(portrait, wrap.firstChild);
  var cells = Array.prototype.slice.call(portrait.querySelectorAll(".c:not(.e)"));

  /* --- fit to the column --- */
  var title = wrap.querySelector(".title-area");
  var titleAt = Number(P.title_at) || 0.7;     // name sits on the shirt, below the face
  function fit() {
    var w = wrap.clientWidth;
    var stacked = window.matchMedia("(max-width: 980px)").matches;
    var s = (w + 110) / P.width;
    if (!stacked) s = Math.min(s, (window.innerHeight * 0.98) / P.height);
    s = Math.max(0.45, Math.min(s, 1.15));
    portrait.style.transform = "scale(" + s + ")";
    if (title) title.style.top = (10 + P.height * titleAt * s) + "px";
    if (stacked) {
      var titleH = title ? title.offsetHeight : 0;
      wrap.style.height = Math.max(P.height * s * 0.95, 10 + P.height * titleAt * s + titleH + 20) + "px";
    } else {
      wrap.style.height = "";
    }
  }
  fit();
  window.addEventListener("resize", fit);
  if (document.fonts && document.fonts.ready) document.fonts.ready.then(fit);

  /* --- living bits --- */
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches || !cells.length) return;
  setInterval(function () {
    if (document.hidden) return;
    for (var k = 0; k < 40; k++) {
      var c = cells[(Math.random() * cells.length) | 0];
      c.textContent = c.textContent === "0" ? "1" : "0";
    }
  }, 90);

  /* hover: bits near the mouse flash gold */
  portrait.style.pointerEvents = "none";
  var last = 0;
  wrap.addEventListener("mousemove", function (e) {
    var now = Date.now();
    if (now - last < 40) return;
    last = now;
    portrait.style.pointerEvents = "auto";
    var hit = document.elementFromPoint(e.clientX, e.clientY);
    portrait.style.pointerEvents = "none";
    if (!hit || !hit.classList || !hit.classList.contains("c") || hit.classList.contains("e")) return;
    var row = hit.parentNode;
    var idx = Array.prototype.indexOf.call(row.children, hit);
    [row.previousSibling, row, row.nextSibling].forEach(function (r) {
      if (!r || !r.children) return;
      for (var d = -2; d <= 2; d++) {
        var c = r.children[idx + d];
        if (c && !c.classList.contains("e")) flash(c);
      }
    });
  });
  function flash(c) {
    c.classList.add("flash");
    c.textContent = c.textContent === "0" ? "1" : "0";
    setTimeout(function () { c.classList.remove("flash"); }, 450);
  }
})();
